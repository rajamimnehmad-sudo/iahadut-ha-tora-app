export function newProductCategoryPath(product) {
  const title=String(product?.title||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().split(/\bmarca\b/)[0].trim();
  const match=rules.find(([,pattern])=>pattern.test(title));
  return match ? [...match[0]] : null;
}
